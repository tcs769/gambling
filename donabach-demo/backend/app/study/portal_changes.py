"""Before and after for each change the demo precomputes: the mix, the wealth at 80, this year's moves and the comparison figures.

    python -m app.study.portal_changes [--out ../reports/waramoug_changes.md]
"""

from __future__ import annotations

import argparse
import time
from pathlib import Path

from app.portal import engine_view as E
from app.portal import presets


def _m(x: float) -> str:
    return f"${x:,.0f}"


def _moves(plan) -> str:
    out = []
    for m in plan.portfolio.overview.moves:
        status = {"done": "Done", "ongoing": "Ongoing", "scheduled": "Scheduled", "needs_ok": "Needs your OK", "your_step": "Your step"}[m.status]
        amount = f" {_m(m.amount)}" if m.amount is not None else ""
        out.append(f"{m.title}{amount} ({m.timing}, {status})")
    return "<br>".join(out)


def _mix(plan) -> str:
    return ", ".join(f"{r.label} {r.share:.1%}" for r in plan.portfolio.overview.mix.rows if r.share > 0)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--out", type=Path, default=Path("../reports/waramoug_changes.md"))
    args = parser.parse_args()
    started = time.perf_counter()
    ids = presets.precompute()
    seconds = time.perf_counter() - started
    base = E.lookup(ids["base"])
    lines = [
        "# What each precomputed change does to John Smith's portfolio",
        "",
        f"Generated by `python -m app.study.portal_changes` (all {len(presets.PRESETS) + 1} portfolios in {seconds:.0f} s on this machine, kernels already compiled). "
        "Each change runs the real planner on the changed household; the current portfolio's strategy is kept unless the search finds one that is clearly better. "
        "Every figure is the engine's.",
        "",
        "| | Overall mix | Wealth at 80 (Waramoug) | Standard advisor | More at 80 | A year | Roth conversion this year | Next year | Tax saved this year |",
        "|---|---|---|---|---|---|---|---|---|",
    ]

    def row(name, p):
        c, s = p.comparison, p.portfolio.summary
        moves = {m.key: m for m in p.portfolio.overview.moves}
        this = moves.get("conversion")
        nxt = moves.get("conversion_next")
        lines.append(
            f"| {name} | {_mix(p)} | {_m(s.projected_wealth)} | {_m(c.advisor.wealth_80)} | {_m(c.dollars_more)} | {c.rate_per_year:+.2%} | "
            f"{_m(this.amount) if this else 'none'} | {(_m(nxt.amount) + ' at ' + str(nxt.age)) if nxt else 'none'} | {_m(s.tax_saved)} |"
        )

    row("Base (John Smith as read)", base)
    for preset in presets.PRESETS:
        plan = E.lookup(ids[preset.key])
        row(preset.label, plan)
    lines += ["", "## This year's moves", ""]
    lines.append(f"**Base**: {_moves(base)}")
    for preset in presets.PRESETS:
        plan = E.lookup(ids[preset.key])
        lines += ["", f"**{preset.label}**: {_moves(plan)}"]
    args.out.write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
