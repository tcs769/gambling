"""What tax lots change for the sample household: its recommendation and annualized advantage after each of the four steps.

0. Average-cost sales, every gain long-term: how every result was computed before tax lots existed.
1. Donabach sells the highest-cost lots first (the advisors still sell at the average cost).
2. The advisors sell the oldest lots first (first in, first out).
3. Gains on lots held a year or less are taxed as ordinary income, for every strategy: the engine as it now is.

Each stage searches the planning style's strategy menu on 400 futures and scores the winner on 2,000 others, for five seeds
(the first is the app's own). Nothing is tuned: the stages differ only in the lot rules.

    python -m app.study.tax_lots --out ../reports/tax_lots.md
"""

from __future__ import annotations

import argparse
import time
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path

from app.planner.baseline import RIA_BASELINE, TYPICAL_ADVISOR
from app.planner.strategies import Strategy, menu
from app.schemas import Household
from app.study.measure import DEFAULT_SEEDS, measure_seeds, sample_household


@dataclass(frozen=True)
class Stage:
    name: str
    donabach: str  # "average", "fifo" or "hifo"
    baseline: str
    short_term: bool


STAGES = (
    Stage("0. Before tax lots: sales at the average cost, every gain long-term", "average", "average", False),
    Stage("1. Donabach sells the highest-cost lots first", "hifo", "average", False),
    Stage("2. The advisors sell the oldest lots first", "hifo", "fifo", False),
    Stage("3. Short-term gains are taxed as ordinary income (the engine now)", "hifo", "fifo", True),
)


@contextmanager
def lot_rules(donabach: str, short_term: bool):
    """Every strategy's policy sells its brokerage stock by `donabach` while this is active."""
    original = Strategy.policy
    Strategy.policy = lambda self: original(self).replace(lot_method=donabach, short_term_ordinary=short_term)
    try:
        yield
    finally:
        Strategy.policy = original


def run_stage(household: Household, stage: Stage, style: str, seeds=DEFAULT_SEEDS, n_eval: int = 2000) -> dict:
    baselines = {
        "good_ria": RIA_BASELINE.replace(lot_method=stage.baseline, short_term_ordinary=stage.short_term),
        "typical_advisor": TYPICAL_ADVISOR.replace(lot_method=stage.baseline, short_term_ordinary=stage.short_term),
    }
    with lot_rules(stage.donabach, stage.short_term):
        return measure_seeds(household, seeds=seeds, n_eval=n_eval, strategies=menu(style=style), baselines=baselines)


def run(household: Household | None = None, seeds=DEFAULT_SEEDS, n_eval: int = 2000, styles=("equity_first", "balanced")) -> dict:
    household = household or sample_household()
    return {style: [(stage, run_stage(household, stage, style, seeds, n_eval)) for stage in STAGES] for style in styles}


def _pct(x: float) -> str:
    return f"{x * 100:+.2f}%"


def render(results: dict, seeds=DEFAULT_SEEDS, seconds: float | None = None) -> str:
    lines = [
        "# What tax lots change",
        "",
        "Generated by `python -m app.study.tax_lots`. The sample household (the spec's fictional household), good RIA baseline. "
        f"Each row searches the planning style's strategy menu on 400 futures and scores the winner on {2000:,} futures it never saw; "
        f"the last two columns average {len(seeds)} seeds. Nothing is tuned: the rows differ only in the lot rules.",
        "",
        "* **Lot tracking.** The brokerage stock is the opening position (long-term) plus one lot per year, which takes that "
        "year's reinvested dividends, rebalancing purchases and savings at cost. Loss harvesting is still the aggregate rule: it "
        "lowers every lot's basis in proportion.",
        "* **Sale order.** Donabach sells the lot bought at the highest price first (the least gain per dollar); the advisors sell the oldest first.",
        "* **Short-term gains.** A lot sold in the year it was bought has a short-term gain, one sold the next year a half-short-term "
        "gain (purchases and sales are spread through a year, so it has been held more than a year half the time), an older one a "
        "long-term gain. The short-term part is ordinary income, net of short-term and long-term losses.",
        "",
    ]
    for style, stages in results.items():
        lines += [
            f"## {'Equity-first' if style == 'equity_first' else 'Balanced'} planning style",
            "",
            "| Step | The plan's recommendation (seed 2026) | Median advantage | Risk-adjusted | Mean of seeds: median | Mean of seeds: risk-adj. | Runs out of money: plan / good RIA |",
            "|---|---|---|---|---|---|---|",
        ]
        previous = None
        for stage, summary in stages:
            run0 = summary["app_seed_run"]
            held = run0["baselines"]["good_ria"]["held_out"]
            mean = summary["mean"]["good_ria"]["held_out"]
            short = run0["baselines"]["good_ria"]["shortfall"]
            lines.append(
                f"| {stage.name} | {run0['strategy_label']} | {_pct(held['median'])} | {_pct(held['risk_adjusted'])} | "
                f"{_pct(mean['median'])} | {_pct(mean['risk_adjusted'])} | {short['plan']:.1%} / {short['baseline']:.1%} |"
            )
            previous = (held, mean)
        lines.append("")
        base_held = stages[0][1]["app_seed_run"]["baselines"]["good_ria"]["held_out"]
        last_held = stages[-1][1]["app_seed_run"]["baselines"]["good_ria"]["held_out"]
        base_mean = stages[0][1]["mean"]["good_ria"]["held_out"]
        last_mean = stages[-1][1]["mean"]["good_ria"]["held_out"]
        lines += [
            f"All four steps together move the median advantage from {_pct(base_held['median'])} to {_pct(last_held['median'])} "
            f"(seed 2026) and from {_pct(base_mean['median'])} to {_pct(last_mean['median'])} (mean of seeds); the risk-adjusted advantage from "
            f"{_pct(base_held['risk_adjusted'])} to {_pct(last_held['risk_adjusted'])} and from {_pct(base_mean['risk_adjusted'])} to "
            f"{_pct(last_mean['risk_adjusted'])}.",
            "",
        ]
    if seconds is not None:
        lines.append(f"_Computed in {seconds:,.0f} seconds._")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=None)
    parser.add_argument("--seeds", type=int, default=len(DEFAULT_SEEDS))
    parser.add_argument("--n-eval", type=int, default=2000)
    args = parser.parse_args(argv)
    started = time.perf_counter()
    seeds = DEFAULT_SEEDS[: args.seeds]
    text = render(run(seeds=seeds, n_eval=args.n_eval), seeds, time.perf_counter() - started)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text)
    print(text)


if __name__ == "__main__":
    main()
